import fs from "node:fs";
import path from "node:path";
import { registerAllCommands } from "../src/commands";
import { CommandRegistry } from "../src/commands/registry";
import { SCOPE_HELP } from "../src/auth/access";
import type { Services } from "../src/core/services";

// Registration only stores definitions; handlers use the services lazily, so an empty object is enough here.
const reg = new CommandRegistry();
registerAllCommands(reg, {} as Services);

const byGroup = new Map<string, ReturnType<CommandRegistry["list"]>>();
for (const d of reg.list()) byGroup.set(d.group, [...(byGroup.get(d.group) ?? []), d]);

const out: string[] = [
  "# Command reference",
  "",
  "Generated by `npm run docs:commands` from the live command registry.",
  "",
  "On the **userbot** commands start with the prefix (default `.`); on the **control bot** they start with `/`.",
  "Options look like `--chat=@name`, flags like `--yes`. Destructive commands always show a dry-run first (see SECURITY.md).",
  "",
  "## Permission scopes (self mode)",
  "",
  ...Object.entries(SCOPE_HELP).map(([k, v]) => `- \`${k}\` — ${v}`),
  "- `master` — only the master admin from `.env`",
  "",
];
for (const [group, defs] of byGroup) {
  out.push(`## ${group}`, "", "| Command | Scope | What it does |", "| --- | --- | --- |");
  for (const d of defs) out.push(`| \`${d.usage.replace(/\|/g, "\\|")}\` | ${d.scope} | ${d.description.replace(/\|/g, "\\|")} |`);
  out.push("");
}
const file = path.join(process.cwd(), "docs", "COMMANDS.md");
fs.writeFileSync(file, out.join("\n"));
console.log(`wrote ${path.relative(process.cwd(), file)} (${reg.list().length} commands)`);
